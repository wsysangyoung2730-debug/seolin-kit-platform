const {
  withDangerousMod,
  withGradleProperties,
} = require("expo/config-plugins");
const { mkdir, writeFile } = require("node:fs/promises");
const path = require("node:path");

module.exports = function withAndroidBuildJdk(config) {
  config = withGradleProperties(config, (config) => {
    config.modResults = config.modResults.filter(
      (item) =>
        item.type !== "property" || item.key !== "reactNativeDevServerPort",
    );
    // Android Studio Run must connect to the same Metro port as the CLI.
    config.modResults.push({
      type: "property",
      key: "reactNativeDevServerPort",
      value: "8082",
    });
    return config;
  });
  return withDangerousMod(config, [
    "android",
    async (config) => {
      const gradle = path.join(config.modRequest.platformProjectRoot, "gradle");
      await mkdir(gradle, { recursive: true });
      // Keep CLI and IDE builds on the React Native recommended JDK.
      // Daemon criteria take precedence over JAVA_HOME in recent Gradle versions.
      await writeFile(
        path.join(gradle, "gradle-daemon-jvm.properties"),
        "# Generated by Seolin Tool Expo config; install JDK 17 before building.\ntoolchainVersion=17\n",
      );
      return config;
    },
  ]);
};
