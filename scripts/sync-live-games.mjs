import { readFile, writeFile, readdir, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../miniapps/live-games/', import.meta.url);
await mkdir(new URL('generated/', root), {recursive:true});
for (const [name,file] of [['bootstrap','shared/bootstrap.js'],['score','shared/score.js'],['theme','shared/theme.css']]) {
 await writeFile(new URL(`generated/${name}.ts`,root),`// Generated by scripts/sync-live-games.mjs; edit ${file}.\nexport default ${JSON.stringify(await readFile(new URL(file,root),'utf8'))};\n`);
}
const hashes={};
for(const file of (await readdir(new URL('sources/',root))).filter(f=>f.endsWith('.html')).sort()) {
 const source=await readFile(new URL('sources/'+file,root),'utf8');
 hashes[file]=createHash('sha256').update(source).digest('hex');
 await writeFile(new URL('generated/'+file.replace('.html','.ts'),root),`// Original HTML, generated without modification.\nexport default ${JSON.stringify(source)};\n`);
}
await writeFile(new URL('source-hashes.json',root),JSON.stringify(hashes,null,2)+'\n');
